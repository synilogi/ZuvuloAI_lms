/* ─── Curriculum builders ───────────────────────────────────────────────── */

const TYPE: Record<string, LessonType> = { v: 'video', r: 'reading', d: 'document', l: 'live', p: 'practice', a: 'assignment', q: 'assessment' };

type LessonSpec = [type: keyof typeof TYPE, title: string, minutes: number, flags?: { preview?: boolean; draft?: boolean }];

function chapters(
  courseId: string,
  updatedAt: string,
  specs: { title: string; summary: string; objective?: string; draft?: boolean; lessons: LessonSpec[] }[],
): Chapter[] {
  return specs.map((spec, ci) => {
    const chapterId = `${courseId}-c${ci + 1}`;
    const status: ContentStatus = spec.draft ? 'draft' : 'published';
    return {
      id: chapterId,
      title: spec.title,
      summary: spec.summary,
      objective: spec.objective,
      status,
      lessons: spec.lessons.map(([t, title, durationMin, flags], li): Lesson => ({
        id: `${chapterId}-l${li + 1}`,
        title,
        type: TYPE[t],
        durationMin,
        isPreview: flags?.preview,
        status: spec.draft || flags?.draft ? 'draft' : 'published',
        updatedAt,
      })),
    };
  });
}

