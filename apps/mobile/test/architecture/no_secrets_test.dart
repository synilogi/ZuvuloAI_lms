import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import 'source_scan.dart';

/// No secret, key or token is committed with the app (modules.md §18, workflow §6.4).
final secretPatterns = [
  RegExp(r'rzp_(live|test)_[A-Za-z0-9]+'),
  RegExp(r'\bsk_(live|test)_[A-Za-z0-9]+'),
  RegExp(r'-----BEGIN [A-Z ]*PRIVATE KEY-----'),
  RegExp(r'AIza[0-9A-Za-z_\-]{35}'),
  RegExp(r'eyJ[A-Za-z0-9_\-]{10,}\.eyJ[A-Za-z0-9_\-]{10,}'),
  // The keyword must start the name, so a label like "fieldPassword": "Password" is not a secret.
  RegExp(
    r'''(?<![A-Za-z])(secret|api[_\-]?key|password|passwd|token|signature)\s*["']?\s*[:=]\s*["'][^"'\s]{8,}["']''',
    caseSensitive: false,
  ),
];

final _firebaseApiKey = RegExp(r'AIza[0-9A-Za-z_\-]{35}');

/// Firebase's client configuration, generated by `flutterfire configure`. Its API key identifies the
/// Firebase project to Google and ships inside every build by design — it is not a secret. What protects it
/// is the key's restrictions in Google Cloud (the app's package and signing-certificate SHA-1, and only the
/// Firebase APIs the app calls). Only this key is allowed here; every other pattern is still checked.
const _firebaseConfigFiles = {'lib/firebase_options.dart', 'android/app/google-services.json'};

const _scannedRoots = ['lib', 'assets', 'config', 'android'];
const _skippedDirectories = ['/build/', '/.gradle/', '/.dart_tool/', '/.cxx/'];
const _binaryExtensions = [
  '.png',
  '.jpg',
  '.jpeg',
  '.webp',
  '.jar',
  '.ttf',
  '.otf',
  '.jks',
  '.keystore',
];

/// Public configuration keys a flavor file may hold (modules.md §24).
const allowedConfigKeys = {
  'ENV_NAME',
  'API_BASE_URL',
  'WEB_BASE_URL',
  'BILLING_CHECKOUT_ENABLED',
  'COURSE_CHECKOUT_ENABLED',
  'CRASH_REPORTING_ENABLED',
  'PUSH_ENABLED',
  // TEMPORARY (testing): the LMS registration falls back to without a join link.
  'DEFAULT_WORKSPACE',
};

Iterable<File> _scannedFiles() sync* {
  for (final root in _scannedRoots) {
    final dir = Directory(root);
    if (!dir.existsSync()) continue;
    for (final entity in dir.listSync(recursive: true)) {
      if (entity is! File) continue;
      final path = entity.path.replaceAll(r'\', '/');
      final skipped =
          _skippedDirectories.any((d) => '/$path'.contains(d)) ||
          _binaryExtensions.any(path.toLowerCase().endsWith) ||
          // Git-ignored, machine-local files: never committed.
          path.endsWith('local.properties') ||
          path.endsWith('key.properties');
      if (skipped) continue;
      yield entity;
    }
  }
}

void main() {
  test('no key-like values in lib, assets, config or android', () {
    final violations = <Violation>[];
    for (final file in _scannedFiles()) {
      final String text;
      try {
        text = file.readAsStringSync();
      } on FileSystemException {
        continue; // not UTF-8 text
      }
      final path = relativePath(file);
      // Only the Firebase client key is set aside in its own config files; anything else there still counts.
      final scanned = _firebaseConfigFiles.contains(path)
          ? text.replaceAll(_firebaseApiKey, '')
          : text;
      violations.addAll(findMatches(path, scanned, secretPatterns));
    }
    expect(violations, isEmpty, reason: violations.join('\n'));
  });

  test('flavor configs hold only the public keys', () {
    for (final flavor in ['dev', 'staging', 'prod']) {
      final file = File('config/$flavor.json');
      expect(file.existsSync(), isTrue, reason: 'config/$flavor.json is missing');
      final values = jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
      final keys = values.keys.toSet();
      expect(keys.difference(allowedConfigKeys), isEmpty, reason: 'config/$flavor.json');
      expect(
        allowedConfigKeys.difference(keys).difference({'DEFAULT_WORKSPACE'}),
        isEmpty,
        reason: 'config/$flavor.json',
      );
      expect(values['ENV_NAME'], flavor);
      // In-app checkout (Razorpay Checkout SDK) is a build switch; the payment control also needs the
      // academy's gateway (`checkoutAvailable`). Only its publishable key ever reaches the app, per order.
      expect(values['BILLING_CHECKOUT_ENABLED'], isA<bool>());
      // Buying a course in the app is a build switch too, and off wherever the store's billing rules apply.
      expect(values['COURSE_CHECKOUT_ENABLED'], isA<bool>());
    }
  });

  test('non-dev flavors use HTTPS', () {
    for (final flavor in ['staging', 'prod']) {
      final values =
          jsonDecode(File('config/$flavor.json').readAsStringSync()) as Map<String, dynamic>;
      expect(values['API_BASE_URL'] as String, startsWith('https://'));
      expect(values['WEB_BASE_URL'] as String, startsWith('https://'));
    }
  });

  test('the Firebase config holds only this app\'s clients', () {
    final config =
        jsonDecode(File('android/app/google-services.json').readAsStringSync())
            as Map<String, dynamic>;
    final packages = [
      for (final client in (config['client'] as List<dynamic>).cast<Map<String, dynamic>>())
        ((client['client_info'] as Map<String, dynamic>)['android_client_info']
            as Map<String, dynamic>)['package_name'],
    ];
    expect(packages, everyElement(startsWith('com.shubhlms.mobile')));
  });

  test('detector catches key-like values', () {
    const sample = '''
const key = 'rzp_live_AbCdEf123456';
const stripe = "sk_test_abc123";
final jwt = 'eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.sig';
const password = 'hunter2hunter2';
"apiKey": "0123456789abcdef"
const fine = 'Enter your password';
"fieldPassword": "Password"
"confirmPassword": "Confirm password"
''';
    expect(findMatches('sample', sample, secretPatterns).map((v) => v.line), [1, 2, 3, 4, 5]);
  });
}
