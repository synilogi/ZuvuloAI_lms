#!/usr/bin/env python3
"""LIVE UI E2E runner: executes the scenarios in scenarios/*.py against the installed dev-flavor app
on a real emulator, records every result as it happens, and keeps the matrix and the per-module
scenario specs in .claude/flutter/e2e/ current.

    tool/live_e2e.sh run                      every eligible module, in dependency order, resuming
    tool/live_e2e.sh run --module FLUTTER-004 one module
    tool/live_e2e.sh run --scenario AUTH-003  one scenario (re-runs it even if it passed)
    tool/live_e2e.sh run --failed             only scenarios whose last result was FAIL
    tool/live_e2e.sh list | docs | inspect

Results are persisted after every scenario (results.json, matrix.md), so a crash resumes at the
first scenario of the current module that has not passed in this run.
"""

from __future__ import annotations

import argparse
import datetime as dt
import importlib
import json
import os
import pkgutil
import sys
import time
import traceback
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from driver import Device, E2EFailure, EnvironmentFailure  # noqa: E402
from harness import REGISTRY, Blocked, Ctx, Scenario  # noqa: E402

MOBILE = HERE.parent.parent
ROOT = MOBILE.parent.parent
E2E_DIR = ROOT / '.claude/flutter/e2e'
RESULTS = E2E_DIR / 'results.json'
MATRIX = E2E_DIR / 'matrix.md'
MODULES = ROOT / '.claude/flutter/modules.json'
EVIDENCE = Path(os.environ.get('E2E_EVIDENCE', MOBILE / '.live_e2e'))


def now() -> str:
    return dt.datetime.now().astimezone().isoformat(timespec='seconds')


def load_scenarios() -> None:
    import scenarios

    for info in pkgutil.iter_modules(scenarios.__path__):
        importlib.import_module(f'scenarios.{info.name}')


def load_results() -> dict:
    if RESULTS.exists():
        return json.loads(RESULTS.read_text())
    return {'environment': {}, 'checkpoint': {}, 'scenarios': {}, 'modules': {}}


def save_results(results: dict) -> None:
    """Writes the results, keeping any fix note recorded on disk meanwhile (`runner.py fix` while
    a run is in progress) instead of overwriting it with this process's older copy."""
    E2E_DIR.mkdir(parents=True, exist_ok=True)
    if RESULTS.exists():
        try:
            on_disk = json.loads(RESULTS.read_text()).get('scenarios', {})
        except ValueError:
            on_disk = {}
        for sid, rec in on_disk.items():
            if rec.get('fix') and rec.get('fix') != results['scenarios'].get(sid, {}).get('fix'):
                results['scenarios'].setdefault(sid, {})['fix'] = rec['fix']
    tmp = RESULTS.with_suffix('.tmp')
    tmp.write_text(json.dumps(results, indent=2, sort_keys=True) + '\n')
    tmp.replace(RESULTS)
    write_matrix(results)


def module_registry() -> list[dict]:
    return json.loads(MODULES.read_text())['modules']


def module_order() -> list[str]:
    mods = module_registry()
    return [m['id'] for m in sorted(mods, key=lambda m: m['priority'])]


def module_rollup(results: dict) -> None:
    by_module: dict[str, list[str]] = {}
    for s in REGISTRY.values():
        if s.tier == 'smoke':
            by_module.setdefault(s.module, []).append(s.id)
    for mod, ids in by_module.items():
        statuses = [results['scenarios'].get(i, {}).get('status', 'NOT RUN') for i in ids]
        if all(st == 'PASS' for st in statuses):
            live = 'PASS'
        elif any(st == 'FAIL' for st in statuses):
            live = 'FAIL'
        elif any(st == 'NOT RUN' for st in statuses):
            live = 'IN PROGRESS' if any(st != 'NOT RUN' for st in statuses) else 'NOT RUN'
        elif all(st in ('PASS', 'BLOCKED') for st in statuses):
            live = 'PASS (with blocked scenarios)' if any(st == 'PASS' for st in statuses) else 'BLOCKED'
        else:
            live = 'IN PROGRESS'
        counts = {k: statuses.count(k) for k in ('PASS', 'FAIL', 'BLOCKED', 'NOT RUN')}
        deferred = sum(1 for x in REGISTRY.values() if x.module == mod and x.tier == 'deep')
        results['modules'][mod] = {'live': live, 'deferred': deferred, **{k.lower().replace(' ', '_'): v for k, v in counts.items()}}


def write_matrix(results: dict) -> None:
    mods = {m['id']: m for m in module_registry()}
    order = module_order()
    lines = [
        '# LIVE UI E2E Test Matrix',
        '',
        'Generated by `apps/mobile/tool/live_e2e/runner.py` after every scenario — do not edit by hand.',
        'Statuses: PASS (seen on the device, with evidence) · FAIL · BLOCKED (external requirement named) ·',
        'NOT RUN · DEFERRED (deep-QA scenario, not run in the fast smoke phase — not a failure).',
        'A module\'s Live E2E status is decided by its **smoke** scenarios only. Development status comes from',
        '`modules.json`; this file records only the live layer.',
        '',
    ]
    env = results.get('environment') or {}
    if env:
        lines += [
            f"Environment: {env.get('avd', '?')} (`{env.get('serial', '?')}`), Android {env.get('android', '?')} / API "
            f"{env.get('api', '?')}, package `{env.get('package', '?')}` (flavor dev), backend {env.get('backend', '?')}",
            '',
        ]
    lines += ['## Modules (smoke phase)', '', '| Module | Name | Development | Live E2E (smoke) | Pass | Fail | Blocked | Not run | Deep deferred |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for mid in order:
        r = results['modules'].get(mid)
        if not r:
            continue
        m = mods.get(mid, {})
        lines.append(
            f"| {mid} | {m.get('name', '')} | {m.get('status', '?')} | **{r['live']}** | {r['pass']} | {r['fail']} | {r['blocked']} | {r['not_run']} | {r.get('deferred', 0)} |"
        )
    lines += ['', '## Scenarios', '', '| Module | Scenario | Tier | Description | Preconditions | Status | Evidence | Failure | Fix | Last run |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    ordered = sorted(REGISTRY.values(), key=lambda s: (order.index(s.module) if s.module in order else 999, s.order))
    for s in ordered:
        r = results['scenarios'].get(s.id, {})
        if s.tier == 'deep' and r.get('tier') != 'deep-run':
            r = {'status': 'DEFERRED (deep QA)', 'fix': r.get('fix')}
        ev = ', '.join(f'`{e}`' for e in r.get('evidence', [])[:3])
        lines.append(
            '| {m} | {id} | {tier} | {t} | {p} | {st} | {ev} | {f} | {fx} | {lr} |'.format(
                m=s.module,
                id=s.id,
                tier=s.tier,
                t=s.title,
                p='; '.join(s.preconditions) or '—',
                st=r.get('status', 'NOT RUN'),
                ev=ev or '—',
                f=_cell(r.get('failure')),
                fx=_cell(r.get('fix')),
                lr=r.get('lastRun', '—'),
            )
        )
    MATRIX.write_text('\n'.join(lines) + '\n')


def _cell(value: str | None) -> str:
    if not value:
        return '—'
    return value.replace('|', '\\|').replace('\n', ' ')[:220]


def write_docs() -> None:
    """One spec file per module, generated from the scenarios' own declarations so the document and
    the executed steps never drift apart."""
    mods = {m['id']: m for m in module_registry()}
    by_module: dict[str, list[Scenario]] = {}
    for s in REGISTRY.values():
        by_module.setdefault(s.module, []).append(s)
    for mid, items in by_module.items():
        items.sort(key=lambda s: s.order)
        slug = items[0].doc_slug
        out = [
            f"# {mid} {mods.get(mid, {}).get('name', '')} — LIVE UI E2E scenarios",
            '',
            'Generated from `apps/mobile/tool/live_e2e/scenarios/` (`tool/live_e2e.sh docs`). Each scenario is',
            'executed on the emulator through the accessibility tree and `adb input` — no code runs inside the app.',
            '',
        ]
        for s in items:
            out += [
                f'## {s.id} — {s.title}',
                '',
                f'- **Module:** {s.module}',
                f'- **Tier:** {s.tier}{" (deferred to the deep-QA phase)" if s.tier == "deep" else ""}',
                f'- **Priority:** {s.priority}',
                f'- **Safe to repeat:** {"yes" if s.repeat_safe else "no"}',
                f'- **Purpose:** {s.purpose}',
                f'- **Preconditions:** {"; ".join(s.preconditions) or "none"}',
                f'- **Test data:** {"; ".join(s.data) or "none"}',
                '',
                '**Actions**',
                '',
                *[f'{i}. {a}' for i, a in enumerate(s.actions, 1)],
                '',
                '**Expected**',
                '',
                *[f'- {e}' for e in s.expected],
                '',
                f'**Evidence:** {"; ".join(s.evidence) or "screenshot of the final state; logcat on failure"}',
                '',
                f'**Cleanup:** {s.cleanup or "none needed"}',
                '',
            ]
        (E2E_DIR / f'{mid}-{slug}.md').write_text('\n'.join(out))


def environment(device: Device) -> dict:
    info = device.assert_ready()
    info.update(device.automation_settings())
    leftover = device.close_system_dialogs()
    if leftover:
        print(f'closed a system dialog left from before this run: {leftover}')
    from harness import Api

    api = Api()
    api.assert_safe()
    relay = Api(os.environ.get('E2E_APP_FACING', 'http://localhost:4200'))
    status, _ = relay.call('GET', '/health')
    if status != 200:
        raise EnvironmentFailure(f'the app-facing relay {relay.base} is not answering (tool/live_e2e/netem.py serve)')
    info['backend'] = f'local contract server {api.base} (scratch database) behind netem relay {relay.base}'
    info['apiBaseUrlInApp'] = api.app_base_url()
    return info


INSTALLED = EVIDENCE / 'installed.json'


def assert_build_under_test(device: Device) -> str:
    """The APK on the emulator must be the one `live_e2e.sh install` put there. Anything else that
    installs the same package (an IDE debug run, another session) silently changes what is tested."""
    try:
        expected = json.loads(INSTALLED.read_text())['lastUpdateTime']
    except (FileNotFoundError, KeyError, ValueError):
        raise EnvironmentFailure('no record of the E2E build being installed — run tool/live_e2e.sh install')
    actual = device.install_stamp()
    if actual != expected:
        raise EnvironmentFailure(
            f'the app under test was replaced: installed {actual}, the E2E build was installed {expected} '
            '(an IDE run or another session installed over it) — reinstall with tool/live_e2e.sh install'
        )
    return expected


def record_install() -> int:
    device = Device()
    device.assert_ready()
    EVIDENCE.mkdir(parents=True, exist_ok=True)
    INSTALLED.write_text(json.dumps({'lastUpdateTime': device.install_stamp(), 'recordedAt': now()}))
    print(f'recorded E2E build install {device.install_stamp()}')
    return 0


def run(args: argparse.Namespace) -> int:
    results = load_results()
    device = Device()
    env = environment(device)
    env['buildInstalledAt'] = assert_build_under_test(device)
    results['environment'] = env
    save_results(results)

    order = module_order()
    selected = sorted(REGISTRY.values(), key=lambda s: (order.index(s.module) if s.module in order else 999, s.order))
    if not args.scenario:
        selected = [s for s in selected if args.tier == 'all' or s.tier == args.tier]
    if args.module:
        selected = [s for s in selected if s.module in args.module]
    if args.scenario:
        selected = [s for s in selected if s.id in args.scenario]
    if args.failed:
        selected = [s for s in selected if results['scenarios'].get(s.id, {}).get('status') == 'FAIL']
    if args.resume and not (args.scenario or args.failed):
        selected = [s for s in selected if results['scenarios'].get(s.id, {}).get('status') not in ('PASS', 'BLOCKED')]

    run_id = dt.datetime.now().strftime('%Y%m%d-%H%M%S')
    print(f'live e2e run {run_id}: {len(selected)} scenario(s) on {env["serial"]} ({env["avd"]}, Android {env["android"]})')
    failures = 0
    for s in selected:
        try:
            assert_build_under_test(device)
        except EnvironmentFailure as e:
            print(f'STOPPED: {e}')
            results['checkpoint'] = {'run': run_id, 'module': s.module, 'scenario': s.id, 'state': f'stopped: {e}'}
            save_results(results)
            return 2
        results['checkpoint'] = {'run': run_id, 'module': s.module, 'scenario': s.id, 'startedAt': now(), 'state': 'running'}
        save_results(results)
        outcome = execute(s, device, run_id)
        prev = results['scenarios'].get(s.id, {})
        attempts = prev.get('attempts', 0) + (1 if outcome['status'] == 'FAIL' else 0)
        record = {
            'module': s.module,
            'title': s.title,
            'status': outcome['status'],
            'lastRun': now(),
            'run': run_id,
            'evidence': outcome['evidence'],
            'failure': outcome.get('failure'),
            'fix': prev.get('fix'),
            'attempts': attempts if outcome['status'] == 'FAIL' else prev.get('attempts', 0),
            'durationSec': outcome['duration'],
            'notes': outcome.get('notes') or None,
            'tier': 'deep-run' if s.tier == 'deep' else None,
        }
        results['scenarios'][s.id] = {k: v for k, v in record.items() if v not in (None, [])}
        results['checkpoint'] = {'run': run_id, 'module': s.module, 'scenario': s.id, 'finishedAt': now(), 'state': outcome['status']}
        module_rollup(results)
        save_results(results)
        mark = {'PASS': '✓', 'FAIL': '✗', 'BLOCKED': '■'}[outcome['status']]
        print(f"  {mark} {s.id:<10} {s.title} ({outcome['duration']}s){'' if outcome['status'] == 'PASS' else ' — ' + (outcome.get('failure') or '')[:300]}")
        failures += outcome['status'] == 'FAIL'
        if outcome['status'] == 'FAIL' and args.stop_on_fail:
            break
    results['checkpoint']['state'] = 'idle'
    module_rollup(results)
    save_results(results)
    write_docs()
    return 1 if failures else 0


def execute(s: Scenario, device: Device, run_id: str) -> dict:
    ctx = Ctx(device=device, scenario=s, evidence_root=EVIDENCE / run_id / s.id)
    device.logcat_clear()
    started = time.monotonic()
    status, failure = 'PASS', None
    try:
        s.fn(ctx)
        errors = device.flutter_errors()
        if errors:
            raise E2EFailure('the app logged uncaught errors during the scenario:\n' + '\n'.join(errors[:8]))
        if not ctx.evidence:
            ctx.shot('final')
    except Blocked as b:
        status, failure = 'BLOCKED', str(b)
    except (E2EFailure, EnvironmentFailure, AssertionError, Exception) as e:  # noqa: BLE001
        status = 'FAIL'
        kind = 'environment' if isinstance(e, EnvironmentFailure) else 'assertion' if isinstance(e, AssertionError) else 'error'
        failure = f'[{kind}] {e}'.strip()
        try:
            ctx.shot('failure')
            ctx.save('failure-logcat.txt', device.logcat(ctx.evidence_root / 'failure-logcat.txt').read_text())
            ctx.save('failure-screen.txt', device.dump().describe())
            ctx.save('failure-traceback.txt', traceback.format_exc())
        except Exception:  # noqa: BLE001 — evidence capture must not mask the failure itself
            pass
    finally:
        try:
            s.cleanup_fn and s.cleanup_fn(ctx)
        except Exception as e:  # noqa: BLE001
            ctx.notes.append(f'cleanup failed: {e}')
        try:
            device.set_network(True) if ctx.network_touched else None
            ctx.normal_network() if ctx.delay_touched else None
        except Exception:  # noqa: BLE001
            pass
    rel = [str(p.relative_to(EVIDENCE)) for p in ctx.evidence]
    first_line = (failure or '').split('\n--- screen ---')[0]
    return {
        'status': status,
        'failure': first_line[:1200] if failure else None,
        'evidence': rel,
        'duration': round(time.monotonic() - started, 1),
        'notes': '; '.join(ctx.notes) or None,
    }


def main() -> int:
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest='cmd', required=True)
    r = sub.add_parser('run')
    r.add_argument('--module', action='append')
    r.add_argument('--scenario', action='append')
    r.add_argument('--failed', action='store_true')
    r.add_argument('--resume', action='store_true', help='skip scenarios already PASS/BLOCKED')
    r.add_argument('--stop-on-fail', action='store_true')
    r.add_argument('--tier', choices=('smoke', 'deep', 'all'), default='smoke', help='smoke (default) runs the fast pass')
    sub.add_parser('list')
    sub.add_parser('docs')
    sub.add_parser('matrix')
    sub.add_parser('inspect')
    sub.add_parser('record-install')
    fx = sub.add_parser('fix', help='record the fix applied for a scenario failure')
    fx.add_argument('scenario')
    fx.add_argument('text')
    args = p.parse_args()

    load_scenarios()
    if args.cmd == 'run':
        return run(args)
    if args.cmd == 'list':
        res = load_results()['scenarios']
        for s in sorted(REGISTRY.values(), key=lambda s: (module_order().index(s.module), s.order)):
            print(f"{s.module}  {s.id:<10} {s.tier:<5} {res.get(s.id, {}).get('status', 'NOT RUN'):<8} {s.title}")
        return 0
    if args.cmd == 'docs':
        write_docs()
        return 0
    if args.cmd == 'matrix':
        results = load_results()
        module_rollup(results)
        save_results(results)
        return 0
    if args.cmd == 'record-install':
        return record_install()
    if args.cmd == 'inspect':
        d = Device()
        print(d.dump().describe())
        return 0
    if args.cmd == 'fix':
        results = load_results()
        results['scenarios'].setdefault(args.scenario, {})['fix'] = args.text
        save_results(results)
        return 0
    return 2


if __name__ == '__main__':
    sys.exit(main())
